//go:build windows

package storage

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"syscall"
	"time"
	"unicode/utf16"
	"unsafe"
)

const (
	foDelete          = 3
	fofSilent         = 0x0004
	fofNoConfirmation = 0x0010
	fofAllowUndo      = 0x0040
	fofNoErrorUI      = 0x0400
)

type SHFILEOPSTRUCTW struct {
	Hwnd                  uintptr
	WFunc                 uint32
	PFrom                 *uint16
	PTo                   *uint16
	FFlags                uint16
	FAnyOperationsAborted int32
	HNameMappings         uintptr
	LpszProgressTitle     *uint16
}

var (
	shell32 = syscall.NewLazyDLL("shell32.dll")

	shFileOperation = shell32.NewProc("SHFileOperationW")
)

// CleanupOldWallpapers moves previous application-generated
// wallpapers into the Windows Recycle Bin.
func CleanupOldWallpapers(
	downloadDir string,
	currentWallpaper string,
) error {

	absoluteDir, err := filepath.Abs(downloadDir)

	if err != nil {
		return fmt.Errorf("failed to resolve wallpaper directory: %w", err)
	}

	currentPath, err := filepath.Abs(currentWallpaper)

	if err != nil {
		return fmt.Errorf("failed to resolve current wallpaper path: %w", err)
	}

	entries, err := os.ReadDir(absoluteDir)

	if err != nil {
		return fmt.Errorf("failed to read wallpaper directory: %w", err)
	}

	var cleanupErrors []string

	for _, entry := range entries {

		if entry.IsDir() {
			continue
		}

		filename := entry.Name()

		// Only manage files generated by our downloader.
		if !isManagedWallpaper(filename) {
			continue
		}

		filePath := filepath.Join(absoluteDir, filename)

		// Never move today's active wallpaper.
		if samePath(filePath, currentPath) {
			continue
		}

		err := moveToRecycleBin(filePath)

		if err != nil {
			cleanupErrors = append(
				cleanupErrors,
				fmt.Sprintf("%s: %v", filename, err),
			)

			continue
		}
	}

	if len(cleanupErrors) > 0 {
		return fmt.Errorf(
			"some wallpapers could not be moved to Recycle Bin: %s",
			strings.Join(cleanupErrors, "; "),
		)
	}

	return nil
}

// isManagedWallpaper recognizes our timestamp-based filenames.
func isManagedWallpaper(filename string) bool {

	extension := strings.ToLower(filepath.Ext(filename))

	switch extension {
	case ".jpg", ".jpeg", ".png", ".gif":
	default:
		return false
	}

	stem := strings.TrimSuffix(filename, filepath.Ext(filename))

	_, err := time.Parse(
		"2006-01-02-150405.000000000",
		stem,
	)

	return err == nil
}

func samePath(path1, path2 string) bool {

	absolute1, err1 := filepath.Abs(path1)
	absolute2, err2 := filepath.Abs(path2)

	if err1 != nil || err2 != nil {
		return false
	}

	return strings.EqualFold(
		filepath.Clean(absolute1),
		filepath.Clean(absolute2),
	)
}

// moveToRecycleBin uses the Windows Shell API.
func moveToRecycleBin(filePath string) error {

	absolutePath, err := filepath.Abs(filePath)

	if err != nil {
		return fmt.Errorf("failed to resolve file path: %w", err)
	}

	fileInfo, err := os.Stat(absolutePath)

	if err != nil {
		return fmt.Errorf("failed to inspect file: %w", err)
	}

	if !fileInfo.Mode().IsRegular() {
		return fmt.Errorf("path is not a regular file")
	}

	// SHFileOperationW requires a double-null-terminated
	// UTF-16 path list.
	pathUTF16 := append(
		utf16.Encode([]rune(absolutePath)),
		0,
		0,
	)

	operation := SHFILEOPSTRUCTW{
		WFunc: foDelete,
		PFrom: &pathUTF16[0],
		FFlags: fofAllowUndo |
			fofSilent |
			fofNoConfirmation |
			fofNoErrorUI,
	}

	result, _, _ := shFileOperation.Call(
		uintptr(unsafe.Pointer(&operation)),
	)

	if result != 0 {
		return fmt.Errorf(
			"SHFileOperationW failed with code %d",
			result,
		)
	}

	if operation.FAnyOperationsAborted != 0 {
		return fmt.Errorf("recycle operation was aborted")
	}

	return nil
}
